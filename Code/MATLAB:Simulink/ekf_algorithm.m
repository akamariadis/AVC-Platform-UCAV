function y = ekf_algorithm(u)

persistent x_hat P Q R F_k H_k

if isempty(x_hat)
    x_hat = [0; 0]; 
    P = [1, 0; 
         0, 1];
    Q = [1e-6, 0; 
         0,    1e-6]; 
    R = 1e-2; 
    m = 0.5; k = 5000; c = 2.5; Ts = 1/2000;
    Ac = [0,       1; 
         -k/m, -c/m];
    F_k = expm(Ac * Ts); 
    
    H_k = [1, 0];
end

% -------------------------------------------------------------------------
% EKF PREDICT STEP (Priori)
% -------------------------------------------------------------------------
x_hat_minus = F_k * x_hat; 
P_minus = (F_k * P * F_k') + Q;

% -------------------------------------------------------------------------
% EKF UPDATE STEP (Posteriori)
% -------------------------------------------------------------------------
S = (H_k * P_minus * H_k') + R;
K = P_minus * H_k' / S;
x_hat = x_hat_minus + K * (u - (H_k * x_hat_minus));
I_KH = eye(2) - (K * H_k);
P = (I_KH * P_minus * I_KH') + (K * R * K');

% -------------------------------------------------------------------------
% OUTPUT TO DSP
% -------------------------------------------------------------------------
y = H_k * x_hat;

end